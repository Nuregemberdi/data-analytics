-- 5.8  Кайсы имараттарда кызматкерлердин орточо тажрыйбасы 5 жылдан жогору?
--      [суроону өзум туьздум — SQLBolt'та жок]
-- Кутөм: 1 катар — 2w, орточосу 6.0.
--        Себеби 5.4тө эсептелген: 1e -> 4.14, 2w -> 6.00. Бирөө гана 5тен жогору.
SELECT building, ROUND(AVG(years_employed))
FROM employees
GROUP BY building
HAVING AVG(years_employed) > 5;
-- Чыкты: 2w -> 6. Дал келди.
--
-- МААНИЛҮҮСҮ: HAVING'те ROUND ЖОК — тегеректелбеген AVG менен чыпкаланды.
-- Эгер HAVING ROUND(AVG(...)) > 5 деп жазылса, 4.6 -> 5 болуп, чыпкадан
-- өтпөй турган имарат өтуп кетмек. Чыпка ар дайым чийки маани менен иштейт.
--
-- SELECT'теги ROUND бул жерде эч нерсени өзгөрткөн жок, себеби 2w'нин орточосу
-- так 6.00 — бутун сан. Ал эми 1e чыкканда 4.142857... -> 4 болуп, 0.14 жашырылмак.
-- ЭРЕЖЕ: ROUND эң акырында, көрсөтуу учун гана. Чыпкага да, кийинки эсепке да кирбейт.
--
-- СУРОО ТУЬЗУУ УЬЛГУСУ (өзум суроо туьзө баштадым):
--   «Кайсы [ТОП] боюнча [АГРЕГАТ] [ШАРТ]?»
--   ТОП: role / building · АГРЕГАТ: COUNT/AVG/SUM/MAX/MIN · ШАРТ: ...дан көп/аз
--   Текшеруу: бул шартты БИР КАТАРДЫ карап текшере аламбы?
--     ооба -> WHERE   («тажрыйбасы 5 жылдан ашкан кызматкерлер»)
--     жок  -> HAVING  («орточосу 5 жылдан ашкан имараттар» — бир катарда «орточо» жок)
--
-- Биринчи туьзгөн суроом HAVING'ти талап кылган жок эле:
-- «орточодон жогору тажрыйбалуу кызматкерлер» — бул подзапрос, 4-жуманын темасы.
--
-- Экинчи суроом эки башка мааниде окулуп калды:
--   А) орточосу 5тен жогору имараттар      -> HAVING
--   Б) ичинде бир кызматкери 5тен ашкандар -> WHERE
-- САБАК: суроо эки мааниде окулса, ал даяр суроо эмес. Аналитиктин биринчи иши —
-- суроону так кылуу. Жумушта дал ушул суралат.

-- 5.9  Кайсы role боюнча кызматкерлердин орточо тажрыйбасы 4 жылдан жогору?
--      [суроону өзүм түздүм]
-- Чекти 4 деп тандадым, себеби ал топторду чын эле бөлөт:
--   5.2ден: Artist 6.0 · Manager 6.0 · Engineer 3.4
-- Күтөм: 2 катар — Artist менен Manager, экөөндө тең 6.
SELECT role, ROUND(AVG(years_employed))
FROM employees
GROUP BY role
HAVING AVG(years_employed) > 4;
-- Чыкты: Artist 6 · Manager 6. Дал келди.
--
-- ЖООПТУ БУЗУУГА АРАКЕТ: экөө тең 6.0 — демек эки топ барабарбы?
-- Чийки сандар: Artist 2,8,6,7,7 (n=5, сумма 30) · Manager 9,3,6 (n=3, сумма 18)
-- Экөөнүн орточосу чын эле так 6.0 — ROUND эч нерсе жашырган жок.
--
--   range (MAX - MIN):  Artist 8-2 = 6  ·  Manager 9-3 = 6   -> БИРДЕЙ
--   range эки санды гана колдонот, ортодогуларды таштайт. Ошондуктан айырмалай албады.
--
--   variance = SUM((x - орточо)^2) / n   -- ар бир санды колдонот
--     Artist:  (-4,2,0,1,1) -> 16+4+0+1+1 = 22,  22/5 = 4.4
--     Manager: (3,-3,0)     -> 9+9+0     = 18,  18/3 = 6.0
--   Текшерүү: четтөөлөрдүн суммасы ар дайым нөл болушу керек.
--
-- ЖЫЙЫНТЫК: орточосу бирдей, range'и бирдей, BIROK variance'и башка.
-- Manager'дин чачырандысы көбүрөөк, үстүнө n=3 гана -> орточосу ишенимсизирээк.
-- Бир кызматкер кетсе Manager'дин орточосу секирет, Artist'тики секирбейт.
--
-- SQL ҮЧҮН САБАГЫ: AVG муну эч качан эскертпейт. Экөө тең "6" болуп чыгат,
-- программа унчукпайт. Ошондуктан AVG жазган сайын жанына COUNT(*) коюу керек —
-- муну 2.4тө өзүм жазган элем.
--
-- Терминдер: sample size (n) · variance (чачыранды) · outlier (четтеги маани)

-- 5.10  Ар бир имаратта эң тажрыйбалуу жана эң тажрыйбасыз кызматкердин
--       тажрыйбасы канча жыл?   [суроону өзүм түздүм]
-- Күтөм: 2 катар, 3 тилке. (Адегенде "3 катар, 2 тилке" дедим — тескери.
--        Катар менен тилкени алмаштыруу — менин эң көп кайталанган катам.)
-- Сандарды алдын ала эсептей албайм: кимдин кайсы имаратта иштээри жазылган эмес.
SELECT building,
       MAX(years_employed),
       MIN(years_employed),
       MAX(years_employed) - MIN(years_employed) AS experience_range
FROM employees
GROUP BY building;
-- Чыкты: 1e -> MAX 9, MIN 1, range 8
--        2w -> MAX 8, MIN 2, range 6
--
-- Alias жөнүндө: адегенде height_range деп жаздым — "бийиктиктин диапазону".
-- Бул жерде бийиктик жок, тажрыйба бар. Тилкенин аты эмнени ӨЛЧӨГӨНҮН айтышы керек.
-- Туурасы: experience_range.
--
-- Эки имараттын толук сүрөтү (5.4 менен кошуп):
--   1e: n=7, орточо 4.14, range 8   (9 жылдык менен 1 жылдык чогуу иштейт)
--   2w: n=6, орточо 6.00, range 6
-- Кайсынысы "жакшы" деген суроого SQL жооп бербейт — ал максатка көз каранды.
-- Бул Фаза 3 менен 5тин темасы, азыр эмес.

-- 5.11  Эң узун жана эң кыска фильмди тап, алар кайсы режиссёрдуку?  [movies]
--       [суроону өзүм түздүм]
-- Бул суроо АТ сурайт -> GROUP BY жарабайт, топто 14 ат бар.
-- WHERE да жарабайт: WHERE length_minutes = ? деп жазсам, ошол санды билбейм.
-- Аны алуу үчүн подзапрос керек — ал 4-жума.
-- Азыркы курал: ORDER BY + LIMIT. Санды билбей эле болот — иреттеп, башын алам.
--
-- КАТА: адегенде GROUP BY director кошуп жазгам. Бул silent failure:
-- Lasseter'дин тобунда 5 ар түрдүү узундук бар -> SQLite ЫКТЫЯРДУУ бирөөнү тандайт
-- (эң чоңун эмес! мугалим сураганда "эң чоңун алат" дедим — бул да ката),
-- анан мен ошол жалган санды ORDER BY менен иреттеп жаттым.
-- Суроодо "ар бир режиссёр боюнча" деген сөз жок -> топ да жок -> GROUP BY да жок.

SELECT director, length_minutes
FROM movies
ORDER BY length_minutes DESC
LIMIT 1;
-- Чыкты: John Lasseter, 120

SELECT director, length_minutes
FROM movies
ORDER BY length_minutes ASC
LIMIT 1;
-- Чыкты: John Lasseter, 81
--
-- ЖООПТУ БУЗУУГА АРАКЕТ: эки фильмдин узундугу тең 120 болсочу?
-- LIMIT 1 ыктыярдуу бирөөнү алат, экинчисин КӨРСӨТПӨЙТ — мен билбей калам.
-- Текшерүү: LIMIT 2 жазып, эки катарды көзүм менен салыштырам.
--
-- БАЙКОО: эң узун да, эң кыска да — John Lasseter. Бул эмнени билдирет?
-- Мен "факт" дедим — жетишсиз. Ыктымалдык менен текшерүү керек:
--   P(кокусунан алынган фильм Lasseter'дики) = 5/14 = 0.36
--   P(эң кыскасы да аныкы)                   = 4/13 = 0.31
--   P(экөө тең)                              = 0.36 * 0.31 = 0.11
-- Он ишенин биринде эч кандай өзгөчөлүксүз эле ушундай чыгат.
-- Демек бул байкоо "Lasseter ар түрдүү фильм тартат" дегенди ДАЛИЛДЕБЕЙТ.
-- Ал жөн гана эң көп фильм тарткан (5, калгандарда 1-2ден).
--
-- Түшүнүктүн аты: BASE RATE — салыштыруудан мурун ар бир топтун көлөмүн кара.
-- Эки рефлекс суроосу дал ушул үчүн:
--   1) Эмне менен салыштырылды?
--   2) Ал эки топ дагы эмнеси менен айырмаланат?   (бул жерде: көлөмү менен)

-- 5.12  Кайсы режиссёрлордун career span'и 2 жылдан ашык?   [movies]
--       [суроону өзүм түздүм]
-- CAREER SPAN = MAX(year) - MIN(year). Бул year боюнча алынган range.
-- Күтөм: максимум 4 катар. Себеби бир гана фильм тарткан режиссёрдун
--        MAX(year) = MIN(year) -> span = 0 -> чыпкадан өтпөйт.
--        2.2деги бөлүштүрүү: 5,2,2,2,1,1,1 -> бирден көп фильми барлар 4.
SELECT director,
       MAX(year),
       MIN(year),
       MAX(year) - MIN(year) AS career_span
FROM movies
GROUP BY director
HAVING MAX(year) - MIN(year) > 2;
-- Чыкты: Stanton 2003-2008 -> 5 · Bird 2004-2007 -> 3
--        Lasseter 1995-2011 -> 16 · Docter 2001-2009 -> 8
--        4 катар — максимум менен дал келди, төртөө тең өттү.
--
-- КАТАЛАРЫМ:
-- 1) "AS career span" деп жаздым — боштук менен. SQL үчүн бул бир ат эмес.
--    Туурасы snake_case: career_span
-- 2) Тилкелердин тизмеси менен FROM'дун ортосуна ашыкча үтүр койдум.
-- 3) Фильмдин САНЫ менен career SPAN'ди аралаштырдым. Экөө башка нерсе:
--    эки гана фильм тарткан режиссёр 1998 жана 2010да тартса, span'и 12 жыл.
--
-- ПОРТАТИВДҮҮЛҮК (маанилүү):
-- Адегенде HAVING career_span > 2 деп жаздым. SQLite'та иштейт,
-- бирок PostgreSQL'де ИШТЕБЕЙТ. Себеби стандарт SQL'де HAVING SELECT'тен
-- МУРУН аткарылат -> ал учурда alias дагы жаралып үлгүрбөйт.
-- Ошондуктан HAVING'те туюнтманы кайра жазам: MAX(year) - MIN(year) > 2
-- Бул 5.7деги silent failure сабагы менен бир катарда: SQLite кечиримдүү,
-- PostgreSQL катаал. 4-жумада PostgreSQL'ге өткөндө ушулар чыгат.

-- 5.13  2000-жылга чейин тартылган фильмдеринин орточо узундугу
--       90 мүнөттөн ашкан режиссёрлор кимдер?   [movies]
--       [суроону өзүм түздүм — WHERE + GROUP BY + HAVING үчөө чогуу]
-- Ирети: WHERE (катарларды) -> GROUP BY (режиссёр боюнча) -> HAVING (топторду)
SELECT director, AVG(length_minutes)
FROM movies
WHERE year < 2000
GROUP BY director
HAVING AVG(length_minutes) > 90;
-- Чыкты: 0 катар.
--
-- КАТА: адегенде GROUP BY year деп жаздым, SELECT'те director турганда.
-- Бир жылдын тобунда бир нече режиссёр болушу мүмкүн -> director ыктыярдуу
-- тандалат -> silent failure. Суроо режиссёрлор жөнүндө эле -> GROUP BY director.
--
-- НОЛЬ КАТАР — КАТАБЫ ЖЕ ЖООПБУ? Текшерүү методу: чыпканы алып сал,
-- артында эмне турганын кара.
SELECT director, AVG(length_minutes)
FROM movies
WHERE year < 2000
GROUP BY director;
-- Чыкты: John Lasseter — 89.66666666666667
--
-- Эки нерсе ачылды:
-- 1) 2000-жылга чейин БИР ГАНА режиссёр фильм тарткан. "Режиссёрлор" деген
--    суроодо талапкер бирөө эле болчу.
-- 2) Орточо 89.67, чек 90. Айырма 0.33 мүнөт.
--
-- Ноль катар КАТА ЭМЕС — чыныгы жооп.
--
-- ROUND жөнүндө: ROUND(89.67) = 90, шарт > 90 -> 90 > 90 жалган -> дагы эле ноль.
-- >= болсо гана өтмөк. Чыпка ар дайым чийки маани менен (5.8деги эрежем).
--
-- ROBUST ЭМЕС: жооп 0.33 мүнөткө байланып турат. Бир фильмдин узундугу бир
-- мүнөткө өзгөрсө, жооп тескери болот. Отчётто мындайда "90дан төмөн" деп кесе
-- айтпайм: "чекке абдан жакын (89.67), маалымат бир аз өзгөрсө жыйынтык өзгөрөт".

-- 5.14  Кайсы режиссёрлордун фильмдеринин узундук диапазону 1ден чоң?  [movies]
--       [суроону өзүм түздүм]
-- ЧЕКТИ КАНТИП ТАНДАЙМ (жаңы метод):
--   Чекти ойдон чыгарбайм — маалыматтан алам.
--   1) HAVING'сиз аткарам, бардык сандарды көрөм
--   2) Аларды карайм
--   3) Экиге бөлгөн санды тандайм
--   Мугалимдик аналогия: өтүү баллын коёрдо адегенде упайларды карайсың.
--   Чек өтө төмөн болсо баары өтөт (чыпканын пайдасы жок),
--   өтө жогору болсо эч ким өтпөйт (5.13төгүдөй ноль).
SELECT director,
       SUM(length_minutes),
       MAX(length_minutes) - MIN(length_minutes) AS length_range
FROM movies
GROUP BY director
HAVING MAX(length_minutes) - MIN(length_minutes) > 1;
-- HAVING'сиз чыккан сандар: 39, 9, 3, 1, 0, 0, 0
-- Үч режиссёрдо length_range = 0 -> алар бир гана фильм тарткан
-- (MAX = MIN, айырмасы нөл).
--
-- Чек тандоо: > 30 десем 1 гана өтөт — бул топторду БӨЛБӨЙТ, бир OUTLIER'ди
-- бөлүп алат. Экөө тең туура болушу мүмкүн, бирок кайсынысын кылып жатканымды
-- билишим керек.
-- > 5 -> 2 өтөт · > 1 -> 3 өтөт · >= 1 -> 4 өтөт
-- > 1 тандадым.
-- Чыкты: Stanton 211/3 · Lasseter 506/39 · Docter 193/9. 3 катар, дал келди.
--
-- SUM боюнча Lasseter биринчи (506 мүнөт). Бул анын фильмдери УЗУН дегенби?
-- ЖОК. SUM көлөмдү өлчөйт — карьерасында жалпы канча мүнөт тартканын.
-- Фильмдери узунбу деген суроого AVG жооп берет. Бул 2.5теги сабагым:
-- бир эле маалымат эки башка рейтинг берет. Аты — НОРМАЛДАШТЫРУУ.

-- 5.15  Кайсы режиссёрлор жалпысынан 200 мүнөттөн ашык фильм тарткан?  [movies]
--       [суроону өзүм түздүм]
-- Сандар мурунтан белгилүү: 506, 231, 211, 193, 110, 103, 102
-- Чекти 200 деп тандадым — ал жетөөнү 3 менен 4кө бөлөт.
-- Күтөм: 3 катар, 2 тилке.
SELECT director, SUM(length_minutes) AS total_minutes
FROM movies
GROUP BY director
HAVING SUM(length_minutes) > 200;
-- Чыкты: Stanton 211 · Bird 231 · Lasseter 506. Дал келди.
--
-- HAVING'те alias эмес, SUM(...) туюнтмасын кайра жаздым -> PostgreSQL'де да иштейт.

