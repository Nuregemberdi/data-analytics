-- 3-жума: GROUP BY жана агрегаттар
-- Тема: COUNT, SUM, AVG, MIN, MAX, GROUP BY, HAVING
-- Максат: 40 маселе
-- ============================================
--
-- ЭРЕЖЕ: ар бир query'ди жазардан МУРУН эмне күтөрүңдү жаз.
-- Канча катар, канча тилке, эмне үчүн. Дал келбесе — токто, ойлон.
--
-- ============================================


-- --------------------------------------------
-- 1. Агрегаттар (GROUP BY жок)
-- --------------------------------------------
-- 1.1  Фильмдердин орточо узундугу   [агрегат]
-- Күтөм: 1 катар, 1 тилке. Мааниси 103.5ке жакын — outlier жок
SELECT AVG(length_minutes) FROM movies;
-- Чыкты: 104. Дал келди — медианадан 0.5 гана айырма.
--         Орточо медианадан бир аз жогору → right-skewed.

-- 1.2  Фильмдердин жалпы узундугу   [агрегат]
-- Күтөм: 1456 — AVG × COUNT = 104 × 14. Эсептеп чыгардым, болжолдогон жокмун
SELECT SUM(length_minutes) FROM movies;
-- Чыкты: 1456. Дал келди — формула так иштеди.

-- 1.3  Эң кыска жана эң узун фильм   [агрегат]
-- Күтөм: божомол жазган жокмун — орточо менен медианадан чекти чыгарууга болбойт,
--         бул маалымат query'сиз белгисиз
SELECT MIN(length_minutes) FROM movies;
SELECT MAX(length_minutes) FROM movies;
-- Чыкты: MIN = 81, MAX = 120. Диапазон 39 мүнөт.

-- 1.4  COUNT(*) менен COUNT(director) айырмасы   [агрегат + NULL]
-- Күтөм: экөө тең 14 — 2.1де топтордун суммасы 14 чыккан, демек NULL жок
SELECT COUNT(*), COUNT(director) FROM movies;
-- Чыкты: 14 жана 14. Дал келди — director тилкесинде NULL жок.
--         Эреже: COUNT(*) − COUNT(тилке) = ошол тилкедеги NULLдардын саны.
--         Бул маалыматтын сапатын өлчөйт (missing values).

-- --------------------------------------------
-- 2. GROUP BY
-- --------------------------------------------

-- 2.1  Ар бир режиссёр канча фильм тарткан   [GROUP BY]
-- Күтөм: 7 катар, 2 тилке — DISTINCT director кечээ 7 берген
SELECT director, COUNT(*) FROM movies GROUP BY director;
-- Чыкты: 7 катар, 2 тилке. Дал келди. Эң көбү — John Lasseter, 5 фильм.

-- 2.2  Режиссёрлорду фильм санына карай иреттөө   [GROUP BY + ORDER BY]
-- Күтөм: 7 катар, 2 тилке — ORDER BY санды өзгөртпөйт, ирети гана өзгөрөт
SELECT director, COUNT(*) FROM movies GROUP BY director ORDER BY COUNT(*) DESC;
-- Чыкты: 7 катар. Дал келди. Башындагы үчөө: Lasseter 5, Stanton 2, Bird 2.
--         Текшерүү: 5+2+2+2+1+1+1 = 14 — бир да фильм жоголгон жок.

-- 2.3  Ар бир өлкөдө канча шаар бар   [GROUP BY]
-- Күтөм: 4 катар — АКШ, Канада, Мексика, Куба
SELECT country, COUNT(*) FROM north_american_cities GROUP BY country;
-- Чыкты: 4 катар. US 6, Mexico 3, Canada 2, Cuba 1. Сумма 12 ✅
--         Кечээ "Мексика 3" деп туура тапкам, бирок жалган жол менен:
--         жалпы санды 11 деп алгам жана Кубаны эсепке албагам — эки ката
--         бири-бирин жойгон (compensating errors).

-- 2.4  Ар бир өлкөнүн шаарларынын орточо калкы   [GROUP BY + AVG]
-- Күтөм: 4 катар, 3 тилке. Эң жогоркусу Мексика — Mexico City 8.5 млн
--         үч шаардын бирөө, ошондуктан орточону күчтүү тартат
SELECT country, COUNT(*), AVG(population)
FROM north_american_cities
GROUP BY country
ORDER BY AVG(population) DESC;
-- Чыкты: 4 катар. Башында Мексика.
--         Сабак: топтун көлөмү (sample size, n) кичине болсо орточо ишенимсиз.
--         Кубада n = 1 — анын "орточосу" жалгыз шаардын өз саны, эч нерсе сүрөттөбөйт.
--         Ошондуктан AVG дайыма COUNT(*) менен кошо чыгарылат.

-- 2.5  Ар бир өлкөнүн шаарларынын жалпы калкы   [GROUP BY + SUM]
-- Күтөм: биринчи АКШ — анда шаарлардын саны көп (6), Мексикада 3
SELECT country, SUM(population)
FROM north_american_cities
GROUP BY country
ORDER BY SUM(population) DESC;
-- Чыкты: US 20 271 372 · Mexico 11 798 300 · Canada 4 512 827 · Cuba 2 106 146
--        Дал келди.
--
--        МААНИЛҮҮ: бир эле маалымат эки башка рейтинг берет.
--        Орточо боюнча:  1-Мексика (3.93 млн), 2-АКШ (3.38 млн)
--        Жалпы боюнча:   1-АКШ (20.3 млн),     2-Мексика (11.8 млн)
--        Экөө тең туура, бирок башка суроого жооп берет:
--          жалпы  → кайсы өлкөдө көбүрөөк адам жашайт?
--          орточо → кайсы өлкөнүн шаарлары ирирээк?
--        Отчётто кайсы өлчөм колдонулганын сөзсүз жазуу керек.

-- 2.6  Калкы 2-5 млн ортосундагы шаарлар кайсы өлкөлөрдө   [өз суроом]
-- Күтөм: 2 өлкө. Жогорку чек 4 — таблицада бардыгы 4 гана өлкө бар
SELECT country, COUNT(*)
FROM north_american_cities
WHERE population BETWEEN 2000000 AND 5000000
GROUP BY country;
-- Чыкты: 3 өлкө — US 3, Canada 1, Cuba 1. ЖАҢЫЛДЫМ, бирөөнү кем эсептедим.
--        Кубаны эсептен чыгарып жибериптирмин: Havana 2.1 млн, чектин ичинде.
--
--        Жазуу учурундагы каталарым:
--        1) Адегенде HAVING SUM(population) жазгам — ал өлкөнүн ЖАЛПЫ калкын
--           чыпкалайт, шаарды эмес. Суроо шаарлар жөнүндө эле → WHERE керек.
--        2) Анан GROUP BY'ды таштап жиберип, шаарлардын тизмесин алгам —
--           "кайсы өлкөлөрдө" деген бөлүк жоголуп калган.
--        3) Божомолум "4-5" болчу — а таблицада 4 гана өлкө бар, 5 мүмкүн эмес.
--           Sanity check: жооп жогорку чектен ашпашы керек.

-- --------------------------------------------
-- 3. HAVING
-- --------------------------------------------
--
-- WHERE менен HAVING: айырмасы
--
-- WHERE  катарларды чыпкалайт, топтоодон МУРУН иштейт.
-- HAVING топторду чыпкалайт,  топтоодон КИЙИН иштейт.
--
-- Ошондуктан WHERE'ге COUNT(*) жазууга болбойт — ал учурда COUNT(*) иштей элек,
-- топтор дагы түзүлө элек, демек санай турган нерсе жок.
--

-- 3.1  Бирден көп фильм тарткан режиссёрлор   [HAVING]
-- Күтөм: 4 катар — бөлүштүрүү 5,2,2,2,1,1,1. Бирден жогорусу төртөө
SELECT director, COUNT(*) FROM movies GROUP BY director HAVING COUNT(*) > 1;
-- Чыкты: 4 катар. Дал келди.

-- 3.2  Бирден көп шаары бар өлкөлөр   [HAVING]
-- Күтөм: 3 катар — 2.3те US 6, Mexico 3, Canada 2, Cuba 1. Куба гана түшөт
SELECT country
FROM north_american_cities
GROUP BY country
HAVING COUNT(*) > 1;
-- Чыкты: 3 катар — Canada, Mexico, United States. Дал келди.

-- 3.3  2 млндон ашкан шаарлары бирден көп болгон өлкөлөр   [WHERE + GROUP BY + HAVING]
-- Күтөм: аз катар — 2 млндон ашкан шаарлар 7ге жакын, алар өлкөлөргө бөлүнөт
SELECT country, COUNT(*) AS city_count
FROM north_american_cities
WHERE population > 2000000
GROUP BY country
HAVING COUNT(*) > 1;
-- Чыкты: 1 катар — United States, 4 шаар.
--        Мааниси: 2 млндон ашкан шаарлардын көбү АКШда топтолгон,
--        калган өлкөлөрдө бирден гана.
--        Ирети: WHERE (шаарларды) → GROUP BY (өлкө боюнча) → HAVING (топторду).
--        AS city_count — alias, натыйжадагы тилкеге окулуучу ат берет.

-- 3.4  Орточо узундугу 100 мүнөттөн ашкан режиссёрлор   [HAVING + AVG]
-- Күтөм: 3-4 катар — жарымына жакыны деп ойлодум
SELECT director, COUNT(*)
FROM movies
GROUP BY director
HAVING AVG(length_minutes) > 100;
-- Чыкты: 6 катар. ЖАҢЫЛДЫМ — 3-4 күттүм.
--        Себеби: бүт тизменин орточосу 104, чек 100 андан ТӨМӨН турат,
--        ошондуктан көпчүлүк аны кечип өтөт.
--        Эреже: чек орточодон төмөн болсо, көпчүлүк өтөт.
--        Дагы бир көйгөй: 3 режиссёрдун COUNT(*) = 1 — алардын "орточосу"
--        бир фильмдин өз узундугу, эч нерсе сүрөттөбөйт.

-- 3.5  Ошол эле, бирок ишенимдүү орточолор гана   [HAVING + AND]
-- Күтөм: 3кө жакын — бир фильмдик режиссёрлор түшүп калат
SELECT director, COUNT(*)
FROM movies
GROUP BY director
HAVING AVG(length_minutes) > 100 AND COUNT(*) > 1;
-- Чыкты: 3 катар — Lasseter 5, Stanton 2, Bird 2. Дал келди.
--        Тизменин жарымы n=1 болгон режиссёрлор экен.
--        Бул minimum sample size деп аталат: аз байкоодон чыккан орточону
--        чыныгы орточо менен бир катарда көрсөтүүгө болбойт.

-- 3.6  Ар бир режиссёрдун ар бир жылдагы фильмдеринин саны   [эки тилке боюнча GROUP BY]
-- Күтөм: 14 катар. Себеби: режиссёрлор бир жылда эки фильм тартпаса,
--        ар бир (director, year) жубу уникалдуу болот → 14 фильм = 14 топ
SELECT director, year, COUNT(*)
FROM movies
GROUP BY director, year;
-- Чыкты: 14 катар, COUNT(*) мамычасы БҮТ 1. Дал келди, шартым да ырасталды.
--
--        Эки тилке боюнча топтоо: эки фильм бир топко түшүшү үчүн
--        режиссёру ДА, жылы ДА дал келиши керек. Топ бир сан менен эмес,
--        (director, year) ЖУБУ менен аныкталат.
--
--        Тилке кошуу → топтор БӨЛҮНӨТ (finer-grained), эч качан бириктирилбейт.
--        Ошондуктан: топтор(director, year) >= топтор(director)
--        Тилке алып салуу → топтор бириктирилет (coarser).
--
--        КӨЙГӨЙ: бүт топтордо COUNT(*) = 1 болсо, топтоо эч нерсе бербейт —
--        натыйжа баштапкы таблицанын өзү. GROUP BY көп катарды азга кысышы керек,
--        бул жерде кысылуу болгон жок. Демек кесим өтө майда.
--        Чечими: GROUP BY'дан бир тилке алып салуу.

-- 3.7  КАТА: топтолбогон тилкени SELECTке коюу   [silent failure]
-- Кесимди ирилетем деп year'ды GROUP BY'дан алып салдым, бирок SELECTте калтырдым
SELECT director, year, COUNT(*)
FROM movies
GROUP BY director;
-- Чыкты: 7 катар. COUNT туура (Lasseter 5), бирок YEAR ЖАЛГАН.
--        "John Lasseter 1995 5" — а анын фильмдери 1995, 1998, 1999, 2006, 2011.
--        SQLite беш жылдын ичинен кокусунан бирөөнү тандап алган.
--
--        ЭРЕЖЕ: SELECTтеги ар бир тилке экөөнүн бири болушу керек —
--          1) GROUP BY'да турат, же
--          2) агрегаттын ичинде турат: COUNT(), AVG(), MIN(), MAX()
--        year экөөнө тең кирбейт → жооп аныкталбаган.
--
--        PostgreSQL менен MySQL (strict) бул query'ди аткарбайт, ката берет.
--        SQLite унчукпай туура эмес жооп берет — бул SILENT FAILURE.
--        Ката кыйкырса көрөсүң, унчукпаса отчётко кирип кетет.

-- 3.8  Ар бир режиссёрдун иштеген мезгили   [MIN/MAX + конкатенация + alias]
-- 3.7дин туура түрү: year'ды жоготпош үчүн аны агрегаттын ичине салдым
SELECT
    director,
    MIN(year) || '-' || MAX(year) AS years,
    COUNT(*)
FROM movies
GROUP BY director;
-- Чыкты: Lasseter 1995-2011 (5) · Stanton 2003-2008 (2) · Bird 2004-2007 (2)
--        Docter 2001-2009 (2) · Chapman 2012-2012 (1) · Scanlon 2013-2013 (1)
--        Unkrich 2010-2010 (1)
--        Диапазондун туурасы нөл болсо (2012-2012) — бир гана фильм.
--        || — конкатенация, эки маанини бир сапка улайт.
--        AS years — alias, антпесе мамычанын аты "MIN(year) || '-' || MAX(year)"

-- 4.1  COUNT(тилке) менен COUNT(DISTINCT тилке)   [cardinality]
-- Күтөм: 12 менен 4 — таблицада 12 шаар, 4 өлкө бар
SELECT COUNT(country), COUNT(DISTINCT country)
FROM north_american_cities;
-- Чыкты: 12 жана 4. Дал келди.
--        COUNT(DISTINCT) — тилкедеги АР ТҮРДҮҮ маанилердин саны.
--        Англисче термини: cardinality.
--
--        ДИАГНОСТИКА: COUNT(*) = COUNT(DISTINCT тилке) болсо, ал тилке
--        уникалдуу → primary key боло алат.
--        city:     12 = 12  → уникалдуу
--        country:  12 ≠ 4   → уникалдуу эмес
--        director: 14 ≠ 7   → уникалдуу эмес

-- 4.2  2000-жылдан кийин бирден көп фильм тарткан режиссёрлор   [толук pipeline]
-- Божомол айтпай коё бердим — бул ката, дал келди-келбедиби билинбей калды
SELECT director, COUNT(*)
FROM movies
WHERE year > 2000
GROUP BY director
HAVING COUNT(*) > 1
ORDER BY COUNT(*) DESC;
-- Чыкты: 4 катар — Stanton, Bird, Lasseter, Docter, баары 2ден.
--        Текшерүү: 14 фильмдин 3өө 2000-жылга чейин (1995, 1998, 1999),
--        калган 11 фильм 7 режиссёрго бөлүнөт: 4өө экиден, калганы бирден. Дал келет.
--
--        МААНИЛҮҮ: WHERE санды өзгөртөт. Lasseter жалпысынан 5 фильм тарткан,
--        бирок бул тизмеде 2 гана — үчөө чыпкадан өтпөй калды.
--        Демек "Lasseter эң көп фильм тарткан" деген жыйынтык бул query'ден чыкпайт.
--
--        КАЙТАЛАНГАН КАТА: SELECTке year койдум, GROUP BY'да жок эле — 3.7дин так өзү,
--        20 мүнөт мурун жазган. Анан ORDER BY year DESC жаздым, ал да ошол эле ката.
--        Тапшырма "саны боюнча" деген → ORDER BY COUNT(*) DESC болуш керек.
--
--        Clause тартиби толугу менен:
--        SELECT → FROM → WHERE → GROUP BY → HAVING → ORDER BY → LIMIT

-- 4.3  Диагностика көнүгүүсү: бул query'де ката бар   [silent failure таануу]
--   SELECT country, city, AVG(population) FROM north_american_cities GROUP BY country;
-- Диагнозум: city көйгөйлүү — топто көп шаар бар, кайсынысын көрсөтөрүн билбейт. ТУУРА.
-- Оңдоом: GROUP BY country, city — БУЛ ЖАҢЫЛЫШ.
--   Себеби: city уникалдуу → ар бир топто 1 шаар калат → AVG ошол бир шаардын
--   өз калкы болуп калат, орточо эмес. Бул 3.6дагы n=1 көйгөйү.
-- Туура оңдоо: city'ни SELECTтен алып салуу.
SELECT country, AVG(population)
FROM north_american_cities
GROUP BY country;

-- 4.4  Орточо шаар калкы, тегеректелген   [ROUND]
SELECT country, ROUND(AVG(population))
FROM north_american_cities
GROUP BY country
ORDER BY AVG(population) DESC;
-- Чыкты: Mexico 3 932 767 · US 3 378 562 · Canada 2 256 414 · Cuba 2 106 146
--        ROUND(x) — бүтүн санга тегеректейт
--        ROUND(x, 2) — эки ондукка чейин калтырат
--        Эскертүү: Кубанын "орточосу" — бир гана шаардын калкы (n=1).

-- 4.5  Ар бир өлкөнүн эң чоң жана эң кичине шаарынын айырмасы   [MAX - MIN]
-- Күтөм: Мексика менен АКШ жогору — экөөндө тең өтө чоң шаарлар бар
SELECT
    country,
    MAX(population) - MIN(population) AS pop_differ
FROM north_american_cities
GROUP BY country
ORDER BY pop_differ DESC;
-- Чыкты: Mexico 7 054 700 · US 6 892 470 · Canada 1 077 293 · Cuba 0
--        Куба 0: бир гана шаары бар → MAX менен MIN бир эле сан.
--        Диапазон нөл болсо, байкоо бирөө гана — 3.8деги "2012-2012" менен бир белги.
--        Alias'ты ORDER BY'да кайра колдонсо болот (ORDER BY pop_differ DESC).

-- 4.6  Ар бир он жылдыкта канча фильм чыккан   [эсептелген тилке боюнча GROUP BY]
-- Формула: (year / 10) * 10 → 1995 → 1990, 1998 → 1990, 2003 → 2000
-- SQLite'та бүтүн сандар бөлүнгөндө бөлчөк өзү ыргытылат
SELECT
    (year / 10) * 10 AS ten,
    COUNT(*)
FROM movies
GROUP BY (year / 10) * 10
ORDER BY ten;
-- Чыкты: 1990 → 3 · 2000 → 7 · 2010 → 4.  Суммасы 14, сан туура.
--        14 катар ҮЧКӨ кысылды — бул чыныгы топтоо.
--        3.6да 14 катар 14 топко бөлүнүп, эч нерсе берген эмес. Айырмасы ушунда.
--
--        GROUP BY'га тилкенин атын эмес, ФОРМУЛАНЫ жазса болот.
--        Формула SELECTте да, GROUP BY'да да бирдей турушу керек.
--        Мындай тилке таблицада жок, маалыматтан жасалат:
--        англисче термини derived column же computed column.

-- 4.7  Ар бир он жылдыктагы фильмдердин орточо узундугу   [тенденция]
-- Божомол айткан жокмун — экинчи жолу. Ансыз жаңылганымды текшере албайм.
SELECT
    (year / 10) * 10 AS ten,
    COUNT(*),
    ROUND(AVG(length_minutes))
FROM movies
GROUP BY (year / 10) * 10
ORDER BY ten;
-- Чыкты: 1990 → 3 фильм, 90 мүнөт
--        2000 → 7 фильм, 107 мүнөт
--        2010 → 4 фильм, 109 мүнөт
