-- 5.1  Find the longest time that an employee has been at the studio   [sqlbolt 10]
SELECT MAX(years_employed) FROM employees;
-- Чыкты: 9 (Scott K.)
--        Мен адегенде "SELECT name, MAX(years_employed)" деп жаздым — name
--        GROUP BY'да да, агрегатта да жок эле, 4.3төгү эрежени бузат.
--        SQLite'та бул иштеп кетти: query'де ЖАЛГЫЗ MAX() же MIN() турса,
--        ал ошол сапка туура келген name'ди кайтарат — SQLite'тын жеке эрежеси.
--        PostgreSQL'де ката берет.
--        SQLBolt да кабыл алды — текшергич кең, ашыкча мамычаны көрбөйт.
--        САБАК: текшергичтен өтүү туура дегенди билдирбейт.

-- 5.2  For each role, find the average number of years employed   [sqlbolt 10]
-- "for each ..." деген сөз айкашы дайыма GROUP BY'ды билдирет
SELECT role, AVG(years_employed)
FROM employees
GROUP BY role
ORDER BY AVG(years_employed) DESC;
-- Чыкты: Artist 6.0 · Manager 6.0 · Engineer 3.4
--        ORDER BY'да кашааны туура эмес жапкам: AVG(years_employed DESC
--        DESC — иреттөөнүн БАГЫТЫ, функциянын аргументи эмес → кашаанын СЫРТЫНДА.
--        Натыйжа чыга берди, бирок иреттелбей, алфавит тартибинде турду.
--        Дагы бир silent failure.
--        ROUND айырманы жашырат: Engineer 3.4 → 3 болуп чыкты.
--        Artist менен Manager чын эле барабар (экөө тең так 6.0) — муну
--        ROUND'суз натыйжадан гана билдим.
--        Барабар орточо ≠ барабар ишеним:
--          Artist  n=5 (2,8,6,7,7)
--          Manager n=3 (9,3,6) — жайылуусу кең, бирөө өзгөрсө орточо секирет
--        БАЙЛАНЫШ: топтордун саны = COUNT(DISTINCT топтолгон тилке)

-- 5.3  Find the total number of employee years worked in each building   [sqlbolt 10]
-- "total" → SUM (COUNT эмес)
SELECT building, SUM(years_employed)
FROM employees
GROUP BY building;
-- Чыкты: 1e → 29 · 2w → 36.  Суммасы 65, бүт таблица менен дал келет.

-- 5.4  Ошол эле, бирок салыштырууга жарактуу түрдө   [НОРМАЛДАШТЫРУУ]
-- 5.3төн кийин "2w'да тажрыйбалуураак адамдар иштейт" деп жооп бердим — КАТА.
-- Суммадан ал чыкпайт. 20 киши × 2 жыл = 40, а 4 киши × 8 жыл = 32:
-- суммасы аз имаратта тажрыйба көбүрөөк болушу мүмкүн.
SELECT building, SUM(years_employed), COUNT(*), AVG(years_employed)
FROM employees
GROUP BY building;
-- Чыкты: 1e → 29 жыл, 7 киши, 4.14 орточо
--        2w → 36 жыл, 6 киши, 6.00 орточо
--        Жообум туура болуп чыкты, бирок ЖҮЙӨӨМ туура эмес эле.
--        Туура жооп ≠ туура жүйө. Жумушта экинчиси суралат.
--
--        НОРМАЛДАШТЫРУУ (normalization) — ар кандай көлөмдөгү топторду
--        салыштырууга жарактуу кылуу. Формуласы: сумма / топтогу элементтер саны.
--        AVG дегендин өзү ушул:  AVG = SUM / COUNT
--        Ушул үчүн орточо салыштырууга жарайт, сумма жарабайт.
--
--        Бул менин CONTEXT'имде жазылган алсыз жерим эле:
--        "пропорция табуу керек деп айтам, бирок нормалдаштыруу деп айта албайм".

