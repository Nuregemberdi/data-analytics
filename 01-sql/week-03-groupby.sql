-- Күтөм: 5 · 13 кызматкер − 5 Engineer − 3 Manager = 5 Artist.
--        Бирок натыйжада 1 гана КАТАР чыгат: эсептин мааниси 5, катарлар саны 1.
--        (Мен адегенде "5 катар чыгат" дедим — маани менен катарды чаташтырдым.)
