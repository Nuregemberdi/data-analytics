--   1) WHERE биринчи иштейт -> 5 катар калат, баарында role = 'Engineer'
--   2) SUM ошолорду бир катарга чогултат
--   3) role топтолгон эмес, агрегатта да жок -> SQLite ыктыярдуу бирөөнү тандайт
